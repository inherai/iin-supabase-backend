-- ============================================================
-- Email send log (email plan, phase 0b). Run in Supabase SQL Editor. Safe to re-run.
--
-- One row per email the system tried to send: sent, skipped (member turned it off /
-- address suppressed) or failed. Resend webhooks later move a row to delivered,
-- bounced or complained. Used to avoid duplicates (kind + ref_key + email) and to show
-- in admin what went out and to whom.
-- Written only by the API with the service role; RLS on, no policies.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.email_log (
  id           bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind         text        NOT NULL,           -- which email, e.g. 'invite', 'welcome', 'onboarding_reminder_1'
  category     text        NOT NULL,           -- preference category it belongs to
  email        text        NOT NULL,           -- lower-cased recipient
  user_id      uuid,                           -- recipient's account, when she has one
  ref_key      text,                           -- what it is about (invite id, period...) — dedupe key
  status       text        NOT NULL,
  skip_reason  text,
  resend_id    text,
  error        text,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT email_log_status_chk
    CHECK (status IN ('sent', 'skipped', 'failed', 'delivered', 'bounced', 'complained'))
);

-- The same email about the same thing goes to the same address at most once.
CREATE UNIQUE INDEX IF NOT EXISTS email_log_dedupe
  ON public.email_log (kind, ref_key, email)
  WHERE ref_key IS NOT NULL AND status IN ('sent', 'delivered', 'bounced', 'complained');

CREATE UNIQUE INDEX IF NOT EXISTS email_log_resend_id ON public.email_log (resend_id) WHERE resend_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS email_log_created_at ON public.email_log (created_at DESC);
CREATE INDEX IF NOT EXISTS email_log_user ON public.email_log (user_id, created_at DESC);

ALTER TABLE public.email_log ENABLE ROW LEVEL SECURITY;

-- New tables get no data access for the API roles by default; the API writes as service_role.
GRANT SELECT, INSERT, UPDATE, DELETE ON public.email_log TO service_role;
